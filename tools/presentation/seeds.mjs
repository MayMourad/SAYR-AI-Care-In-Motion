import { launch } from './browser.mjs';
import { writeFileSync } from 'node:fs';
const BASE = process.env.SAYR_URL ?? 'https://maymourad.github.io/SAYR-AI-Care-In-Motion';
const OUT = new URL('./out/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const b = await launch();
const page = await (await b.newContext({ viewport: { width: 1600, height: 1000 } })).newPage();
const go = async (id) => { await page.evaluate((id) => (window.location.hash = '#/' + id), id); await page.waitForTimeout(500); };
await page.goto(BASE + '/#/stress'); await page.waitForTimeout(1200);
await page.getByRole('radio', { name: /Staff unavailability/ }).click();
await go('reflow'); await page.getByRole('button', { name: /Reflow again|^Reflow$/ }).first().click().catch(() => {});
await page.waitForSelector('text=Proposed adjustment', { timeout: 90000 });
await go('reflow'); await page.getByRole('button', { name: 'Accept in the simulation' }).click(); await page.waitForTimeout(500);
await go('ledger'); await page.waitForTimeout(1000);
await page.getByRole('button', { name: /Run 8 seeds/ }).click();
await page.waitForFunction(() => /Improved on \d+ of 8/.test(document.body.innerText), null, { timeout: 180000 });
await page.waitForTimeout(8000);
const t = await page.evaluate(() => { const s = [...document.querySelectorAll('section')].find((x) => x.innerText.includes('Evidence across seeds')); return s ? s.innerText : document.body.innerText; });
writeFileSync(OUT + 'seeds.txt', t);
console.log(t.replace(/\n+/g, ' | '));
await b.close();
