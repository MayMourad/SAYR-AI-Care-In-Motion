// Audit of the PUBLISHED SAYR app: dumps visible text of every screen after a fixed, reproducible click path.
import { launch } from './browser.mjs';
import { writeFileSync, mkdirSync } from 'node:fs';
const BASE = process.env.SAYR_URL ?? 'https://maymourad.github.io/SAYR-AI-Care-In-Motion';
const OUT = new URL('./out/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
mkdirSync(OUT, { recursive: true });
const browser = await launch();
const page = await (await browser.newContext({ viewport: { width: 1600, height: 1000 } })).newPage();
const log = {};
const txt = () => page.evaluate(() => document.querySelector('main, .page, #root')?.innerText ?? document.body.innerText);
const go = async (id) => { await page.evaluate((id) => (window.location.hash = '#/' + id), id); await page.waitForTimeout(500); };
await page.goto(BASE + '/#/motion'); await page.waitForTimeout(1500);
log.nav = await page.evaluate(() => [...document.querySelectorAll('nav.rail a, nav.rail button')].map((e) => e.innerText.replace(/\s+/g, ' ')));
const pause = page.locator('button[aria-label="Pause"]'); if (await pause.count()) await pause.click();
log.motion = await txt();
await go('control'); log.control_normal = await txt();
await go('stress'); log.stress_before = await txt();
await page.getByRole('radio', { name: /Staff unavailability/ }).click(); await page.waitForTimeout(500);
log.stress_staff = await txt();
await go('control'); await page.waitForTimeout(400); log.control_staff = await txt();
await go('journeys'); log.journeys = await txt();
await go('board'); log.board = await txt();
await go('control');
await page.getByRole('button', { name: /^Reflow$/ }).click();
await page.waitForSelector('text=Proposed adjustment', { timeout: 90000 }); await page.waitForTimeout(5500);
log.reflow = await txt();
await go('ripple'); await page.getByRole('button', { name: 'Play the ripple' }).click(); await page.waitForTimeout(9000); log.ripple = await txt();
await go('desk'); log.desk_pending = await txt();
await go('reflow'); await page.getByRole('button', { name: 'Accept in the simulation' }).click(); await page.waitForTimeout(700); log.reflow_accepted = await txt();
await go('desk'); log.desk_after = await txt();
await go('ledger'); await page.waitForTimeout(1500); log.ledger = await txt();
await go('my'); log.my = await txt();
await page.locator('button', { hasText: 'About, methods & credits' }).click(); await page.waitForTimeout(500); log.about = await page.evaluate(() => document.body.innerText);
writeFileSync(OUT + 'audit.json', JSON.stringify(log, null, 1));
for (const [k, v] of Object.entries(log)) console.log(`\n===== ${k} =====\n${typeof v === 'string' ? v.slice(0, 2600) : JSON.stringify(v)}`);
await browser.close();
